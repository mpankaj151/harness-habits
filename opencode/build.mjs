import { build } from "esbuild";
import { readFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8"));
const banner = { js: `// ${pkg.name} v${pkg.version} - generated by esbuild, do not edit` };
const common = { bundle: true, format: "esm", platform: "node", target: "es2022", banner, loader: { ".json": "json" } };

await build({ ...common, entryPoints: ["src/index.ts"], outfile: "dist/harness-habits.js" });

const features = ["output-guard"];
for (const f of features) {
  await build({ ...common, entryPoints: [`src/standalone/${f}.ts`], outfile: `dist/features/${f}.js` });
}
console.log("built dist/harness-habits.js and", features.map((f) => `dist/features/${f}.js`).join(", "));
